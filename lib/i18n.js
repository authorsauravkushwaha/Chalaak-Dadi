// Trilingual dictionary — English (main), Hindi (हिन्दी) and Punjabi (ਪੰਜਾਬੀ).
//
// t(lang, "dotted.key") resolves a key with graceful fallback to English, so a
// missing translation can never crash a page. Language metadata (dir, fonts,
// locale for dates/numbers) also lives here so every page formats identically.

export const LANGS = ["en", "hi", "pa"];
export const DEFAULT_LANG = "en";
export const LANG_COOKIE = "cd_lang";

